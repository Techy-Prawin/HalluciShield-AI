def export_csv(records: List[Dict[str, Any]], filepath: Path):
    """Export machine-readable raw records to CSV."""
    if not records:
        return
    fieldnames = list(records[0].keys())
    with open(filepath, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(records)


def export_json(data: Any, filepath: Path):
    """Export JSON data with proper indentation."""
    with open(filepath, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=2)


def generate_latex_table(summary: Dict[str, Any], filepath: Path):
    """
    Generate clean, publication-ready IEEE-style LaTeX table for ACE sensitivity.
    """
    lines = []
    lines.append("% Auto-generated by evaluation/sensitivity/run_sensitivity_analysis.py")
    lines.append("\\begin{table}[htbp]")
    lines.append("\\centering")
    lines.append("\\caption{ACE Hyperparameter Sensitivity Analysis Across Scenarios}")
    lines.append("\\label{tab:ace_sensitivity}")
    lines.append("\\resizebox{\\columnwidth}{!}{%")
    lines.append("\\begin{tabular}{llcccccr}")
    lines.append("\\toprule")
    lines.append("Scenario & Parameter & Value & Min (\\%) & Max (\\%) & Mean (\\%) & Std (\\%) & Robustness \\\\")
    lines.append("\\midrule")

    scenario_labels = {
        "SCENARIO_A": "Scenario A (High)",
        "SCENARIO_B": "Scenario B (Med)",
        "SCENARIO_C": "Scenario C (Low)",
    }

    for sc_key, sc_label in scenario_labels.items():
        if sc_key not in summary["scenarios"]:
            continue
        sc_data = summary["scenarios"][sc_key]
        base_ace = sc_data["baseline_ace"]
        
        lines.append(f"\\multicolumn{{8}}{{l}}{{\\textbf{{{sc_label}}} (Baseline ACE = {base_ace:.1f}\\%)}} \\\\")
        lines.append("\\midrule")
        
        for param, p_data in sc_data["parameters"].items():
            param_symbol = {
                "gamma": "$\\gamma$ (Curvature)",
                "beta": "$\\beta$ (Shrinkage)",
                "delta_overhead": "$\\delta_{\\text{overhead}}$",
                "pi_crit_soft": "$\\pi_{\\text{crit}}$ (Soft gate)",
            }.get(param, param)
            
            lines.append(
                f" & {param_symbol} & $N={p_data['count']}$ & {p_data['min_ace']:.1f} & "
                f"{p_data['max_ace']:.1f} & {p_data['mean_ace']:.1f} & "
                f"$\\pm${p_data['std_dev']:.2f} & {p_data['effect'].split('(')[0].strip()} \\\\"
            )
        lines.append("\\midrule")

    lines.append("\\bottomrule")
    lines.append("\\end{tabular}%")
    lines.append("}")
    lines.append("\\end{table}")

    with open(filepath, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


def generate_plots(records: List[Dict[str, Any]], output_dir: Path):
    """Generate publication-ready visualization curves for γ, β, and δ_overhead."""
    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        print("  [WARN] matplotlib not available; skipping plot generation.")
        return

    # Palette
    colors = {
        "SCENARIO_A": "#2b5c8f",  # Deep Blue
        "SCENARIO_B": "#d97706",  # Amber / Orange
        "SCENARIO_C": "#dc2626",  # Crimson / Red
    }
    markers = {
        "SCENARIO_A": "o",
        "SCENARIO_B": "s",
        "SCENARIO_C": "^",
    }
    labels = {
        "SCENARIO_A": "Scenario A: High Confidence",
        "SCENARIO_B": "Scenario B: Medium Confidence",
        "SCENARIO_C": "Scenario C: Low Confidence (Hard Gate π_crit=0)",
    }

    # Style
    plt.style.use("seaborn-v0_8-whitegrid" if "seaborn-v0_8-whitegrid" in plt.style.available else "default")
    plt.rcParams.update({
        "font.size": 11,
        "axes.labelsize": 12,
        "axes.titlesize": 13,
        "xtick.labelsize": 10,
        "ytick.labelsize": 10,
        "figure.titlesize": 14,
    })

    # --- Plot 1: ACE vs Gamma ---
    fig, ax = plt.subplots(figsize=(7, 4.5), dpi=300)
    for sc in ["SCENARIO_A", "SCENARIO_B", "SCENARIO_C"]:
        recs = [r for r in records if r["scenario"] == sc and r["parameter_name"] in ("gamma", "baseline")]
        recs = sorted(recs, key=lambda x: x["gamma"])
        xs = [r["gamma"] for r in recs]
        ys = [r["ace"] for r in recs]
        ax.plot(xs, ys, marker=markers[sc], color=colors[sc], label=labels[sc], linewidth=2.0, markersize=7)
    
    ax.axvline(1.0, color="#6b7280", linestyle="--", alpha=0.7, label="Production Default (γ=1.0)")
    ax.set_title("ACE Sensitivity to Confidence Curvature Exponent (γ)", fontweight="bold")
    ax.set_xlabel("Curvature Hyperparameter γ")
    ax.set_ylabel("ACE Confidence Score (%)")
    ax.set_ylim(-5, 105)
    ax.legend(loc="center left", frameon=True)
    plt.tight_layout()
    fig.savefig(output_dir / "ace_sensitivity_gamma.png", dpi=300)
    plt.close(fig)

    # --- Plot 2: ACE vs Beta ---
    fig, ax = plt.subplots(figsize=(7, 4.5), dpi=300)
    for sc in ["SCENARIO_A", "SCENARIO_B", "SCENARIO_C"]:
        recs = [r for r in records if r["scenario"] == sc and r["parameter_name"] in ("beta", "baseline")]
        recs = sorted(recs, key=lambda x: x["beta"])
        xs = [r["beta"] for r in recs]
        ys = [r["ace"] for r in recs]
        ax.plot(xs, ys, marker=markers[sc], color=colors[sc], label=labels[sc], linewidth=2.0, markersize=7)
    
    ax.axvline(PRODUCTION_BETA, color="#6b7280", linestyle="--", alpha=0.7, label=f"Production Default (β={PRODUCTION_BETA:.0f})")
    ax.set_title("ACE Sensitivity to Historical Shrinkage Prior Strength (β)", fontweight="bold")
    ax.set_xlabel("Historical Shrinkage Pseudo-Count β")
    ax.set_ylabel("ACE Confidence Score (%)")
    ax.set_ylim(-5, 105)
    ax.legend(loc="center left", frameon=True)
    plt.tight_layout()
    fig.savefig(output_dir / "ace_sensitivity_beta.png", dpi=300)
    plt.close(fig)

    # --- Plot 3: ACE vs Delta Overhead ---
    fig, ax = plt.subplots(figsize=(7, 4.5), dpi=300)
    for sc in ["SCENARIO_A", "SCENARIO_B", "SCENARIO_C"]:
        recs = [r for r in records if r["scenario"] == sc and r["parameter_name"] in ("delta_overhead", "baseline")]
        recs = sorted(recs, key=lambda x: x["delta_overhead"])
        xs = [r["delta_overhead"] * 100.0 for r in recs]
        ys = [r["ace"] for r in recs]
        ax.plot(xs, ys, marker=markers[sc], color=colors[sc], label=labels[sc], linewidth=2.0, markersize=7)
    
    ax.axvline(0.0, color="#6b7280", linestyle="--", alpha=0.7, label="Production Baseline (δ=0%)")
    ax.set_title("ACE Sensitivity to Performance Overhead (δ_overhead)", fontweight="bold")
    ax.set_xlabel("Performance Overhead / Latency Regression (%)")
    ax.set_ylabel("ACE Confidence Score (%)")
    ax.set_ylim(-5, 105)
    ax.legend(loc="center left", frameon=True)
    plt.tight_layout()
    fig.savefig(output_dir / "ace_sensitivity_delta_overhead.png", dpi=300)
    plt.close(fig)

    # --- Plot 4: Combined 3-Panel Figure ---
    fig, axes = plt.subplots(1, 3, figsize=(16, 4.8), dpi=300)

    # Panel 1: Gamma
    ax = axes[0]
    for sc in ["SCENARIO_A", "SCENARIO_B", "SCENARIO_C"]:
        recs = sorted([r for r in records if r["scenario"] == sc and r["parameter_name"] in ("gamma", "baseline")], key=lambda x: x["gamma"])
        ax.plot([r["gamma"] for r in recs], [r["ace"] for r in recs], marker=markers[sc], color=colors[sc], label=labels[sc].split(":")[0], linewidth=1.8)
    ax.axvline(1.0, color="#6b7280", linestyle="--", alpha=0.6)
    ax.set_title("(a) Curvature Exponent $\\gamma$", fontweight="bold")
    ax.set_xlabel("$\\gamma$")
    ax.set_ylabel("ACE (%)")
    ax.set_ylim(-5, 105)

    # Panel 2: Beta
    ax = axes[1]
    for sc in ["SCENARIO_A", "SCENARIO_B", "SCENARIO_C"]:
        recs = sorted([r for r in records if r["scenario"] == sc and r["parameter_name"] in ("beta", "baseline")], key=lambda x: x["beta"])
        ax.plot([r["beta"] for r in recs], [r["ace"] for r in recs], marker=markers[sc], color=colors[sc], label=labels[sc].split(":")[0], linewidth=1.8)
    ax.axvline(10.0, color="#6b7280", linestyle="--", alpha=0.6)
    ax.set_title("(b) Shrinkage Pseudo-Count $\\beta$", fontweight="bold")
    ax.set_xlabel("$\\beta$")
    ax.set_ylabel("ACE (%)")
    ax.set_ylim(-5, 105)

    # Panel 3: Delta Overhead
    ax = axes[2]
    for sc in ["SCENARIO_A", "SCENARIO_B", "SCENARIO_C"]:
        recs = sorted([r for r in records if r["scenario"] == sc and r["parameter_name"] in ("delta_overhead", "baseline")], key=lambda x: x["delta_overhead"])
        ax.plot([r["delta_overhead"] * 100 for r in recs], [r["ace"] for r in recs], marker=markers[sc], color=colors[sc], label=labels[sc].split(":")[0], linewidth=1.8)
    ax.axvline(0.0, color="#6b7280", linestyle="--", alpha=0.6)
    ax.set_title("(c) Performance Overhead $\\delta_{\\text{overhead}}$", fontweight="bold")
    ax.set_xlabel("$\\delta_{\\text{overhead}}$ (%)")
    ax.set_ylabel("ACE (%)")
    ax.set_ylim(-5, 105)

    # Global legend
    handles, lbls = axes[0].get_legend_handles_labels()
    fig.legend(handles, lbls, loc="lower center", bbox_to_anchor=(0.5, -0.05), ncol=3, frameon=True)
    plt.tight_layout(rect=[0, 0.05, 1, 1])
    fig.savefig(output_dir / "ace_sensitivity_combined.png", dpi=300, bbox_inches="tight")
    plt.close(fig)


def run_full_sensitivity_evaluation():
    print("=" * 70)
    print("  ACE Hyperparameter Sensitivity Analysis")
    print("  Evaluating gamma, beta, delta_overhead across Scenarios A, B, C")
    print("=" * 70)

    # Run pass 1
    exp1 = ACESensitivityExperiment(experiment_id="ace-sensitivity-pass1")
    records1 = exp1.run()
    stats1 = exp1.compute_statistics()

    # Run pass 2 for reproducibility check
    exp2 = ACESensitivityExperiment(experiment_id="ace-sensitivity-pass2")
    records2 = exp2.run()
    stats2 = exp2.compute_statistics()

    # Check reproducibility
    print("\n[REPRODUCIBILITY CHECK]")
    assert len(records1) == len(records2), "Record counts differ across runs!"
    differences = 0
    for r1, r2 in zip(records1, records2):
        for k in ["scenario", "parameter_name", "parameter_value", "ace", "f1", "f2", "f3", "f4", "f5", "f6", "pi_comp", "pi_crit"]:
            if r1[k] != r2[k]:
                differences += 1
                print(f"  Mismatch in {k}: {r1[k]} vs {r2[k]}")
    
    if differences == 0:
        print(f"  PASS: 100% bit-for-bit deterministic reproducibility verified across {len(records1)} configurations.")
    else:
        print(f"  FAIL: Found {differences} nondeterministic values!")

    # Output file paths
    csv_path = RAW_DIR / "ace_sensitivity_results.csv"
    json_path = RAW_DIR / "ace_sensitivity_results.json"
    summary_path = PROCESSED_DIR / "ace_sensitivity_summary.json"
    latex_path = PROCESSED_DIR / "ace_sensitivity_table.tex"

    export_csv(records1, csv_path)
    export_json(records1, json_path)
    export_json(stats1, summary_path)
    generate_latex_table(stats1, latex_path)
    generate_plots(records1, PROCESSED_DIR)

    print(f"\n[OUTPUT ARTIFACTS]")
    print(f"  Raw CSV:      {csv_path}")
    print(f"  Raw JSON:     {json_path}")
    print(f"  Summary JSON: {summary_path}")
    print(f"  LaTeX Table:  {latex_path}")
    print(f"  Plots Dir:    {PROCESSED_DIR}")

    # Print summary table to console
    print("\n" + "=" * 70)
    print("  SENSITIVITY ANALYSIS RESULTS SUMMARY")
    print("=" * 70)
    for sc_key, sc_data in stats1["scenarios"].items():
        base = sc_data["baseline_ace"]
        print(f"\n[{sc_key}] Baseline ACE: {base:.1f}%")
        for param, p in sc_data["parameters"].items():
            print(f"  {param:18s} -> Min: {p['min_ace']:5.1f}%, Max: {p['max_ace']:5.1f}%, "
                  f"Mean: {p['mean_ace']:5.1f}%, Std: {p['std_dev']:4.2f}%, MaxDelta: {p['max_abs_delta']:4.1f}% [{p['effect']}]")

    print("\n" + "=" * 70)
    return stats1, records1


if __name__ == "__main__":
    run_full_sensitivity_evaluation()
